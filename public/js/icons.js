export function iconSvg(name) {
  const rows = ICONS[name];
  if (!rows) return '';
  let rects = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < 12) {
      if (row[x] !== '#') { x++; continue; }
      let w = 0;
      while (row[x + w] === '#') w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
      x += w;
    }
  });
  return `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

export function paintIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => { if (!el.firstChild) el.innerHTML = iconSvg(el.dataset.icon); });
}
